import os
import pymysql
import pandas as pd

results_dir = EXPENSE_RESULTS_DIR
reports_dir = EXPENSE_REPORTS_DIR

conn = pymysql.connect(
    host=EXPENSE_DB_HOST,
    port=EXPENSE_DB_PORT,
    user=EXPENSE_DB_USER,
    password=EXPENSE_DB_PASS,
    database=EXPENSE_DB_NAME,
    charset="utf8mb4",
)
query = f"SELECT * FROM `{EXPENSE_DB_TABLE}`"
fact_df = pd.read_sql(query, conn)
conn.close()

fact_df["Month Date"] = pd.to_datetime(fact_df["Reporting Month"], format="%b-%Y")

total_budget = fact_df["Approved Budget"].sum()
total_actual = fact_df["Year-to-Date Actual"].sum()
total_variance = total_actual - total_budget
total_variance_pct = (total_variance / total_budget * 100) if total_budget != 0 else 0

bu_totals = fact_df.groupby("Business Unit")["Total Expense"].sum().sort_values(ascending=False)
top_bu = bu_totals.index[0]
top_bu_val = bu_totals.iloc[0]

cat_totals = fact_df.groupby("Expense Category")["Total Expense"].sum().sort_values(ascending=False)
top_cat = cat_totals.index[0]
top_cat_val = cat_totals.iloc[0]

over_budget = fact_df[fact_df["Budget Variance Pct"] > 5]
over_budget_count = len(over_budget)

monthly_totals = fact_df.groupby("Reporting Month")["Total Expense"].sum()
monthly_pct = monthly_totals.pct_change() * 100
max_moM_month = monthly_pct.idxmax()
max_moM_val = monthly_pct.max()

chart_monthly = "chart_monthly_trend.png"
chart_category = "chart_expense_by_category.png"
chart_clusters = "chart_expense_clusters.png"

# Compute funding type variance rows
fund_var_df = fact_df.groupby("Funding Type")[["Budget Variance", "Budget Variance Pct"]].sum().reset_index()
fund_var_rows = ""
for _, row in fund_var_df.iterrows():
    fund_var_rows += f"<tr><td>{row['Funding Type']}</td><td>${row['Budget Variance']:,.0f}</td><td>{row['Budget Variance Pct']:+.1f}%</td></tr>\n"

